import request from './request'
export const workflowRoot = kind => kind === 'LEAD' ? '/leads' : '/customers'
export const pageLeads = params => request.get('/leads',{params})
export const saveLead = data => data.id ? request.put('/leads/'+data.id,data) : request.post('/leads',data)
export const pageCustomers = (params,pool=false) => request.get(pool?'/customers/pool':'/customers',{params})
export const saveCustomer = data => data.id ? request.put('/customers/'+data.id,data) : request.post('/customers',data)
export const getWorkflowDetail = (kind,id) => request.get(workflowRoot(kind)+'/'+id)
export const workflowFollows = (kind,id) => request.get(workflowRoot(kind)+'/'+id+'/follows')
export const workflowEvents = (kind,id) => request.get(workflowRoot(kind)+'/'+id+'/events')
export const addWorkflowFollow = (kind,id,data) => request.post(workflowRoot(kind)+'/'+id+'/follows',data)
export const assignWorkflowOwner = (kind,id,data) => request.post(workflowRoot(kind)+'/'+id+'/assign',data)
export const workflowOwners = kind => request.get('/workflow/owners',{params:{kind}})
export const workflowDepartments = () => request.get('/workflow/departments')
export const returnLead = (id,reason) => request.post('/leads/'+id+'/return',{reason})
export const closeLead = (id,status,reason) => request.post('/leads/'+id+'/close',{status,reason})
export const convertLead = id => request.post('/leads/'+id+'/convert')
export const requestCustomerPool = (id,reason) => request.post('/customers/'+id+'/pool-requests',{reason})
export const reviewCustomerPool = (id,requestId,data) => request.post('/customers/'+id+'/pool-requests/'+requestId+'/review',data)
export const customerPoolRequests = id => request.get('/customers/'+id+'/pool-requests')
export const claimCustomer = id => request.post('/customers/'+id+'/claim')
export const pageFollows = params => request.get('/customers/follows',{params})
export const pageOpportunities = params => request.get('/opportunities',{params})
export const saveOpportunity = data => data.id ? request.put('/opportunities/'+data.id,data) : request.post('/opportunities',data)
export const opportunityCustomers = keyword => request.get('/workflow/customer-options',{params:{keyword}})
